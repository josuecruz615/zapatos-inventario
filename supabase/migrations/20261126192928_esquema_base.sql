-- ---------------------------------------------------------------------
-- Vistas (respetan RLS gracias a security_invoker)
-- ---------------------------------------------------------------------
create view public.v_inventario with (security_invoker = true) as
select
  p.id, p.codigo, p.nombre, p.marca_id, m.nombre as marca, p.descripcion,
  p.precio, p.costo, p.imagen_url, p.activo, p.created_at, p.updated_at,
  coalesce(sum(t.existencia), 0)::int as existencia_total,
  coalesce(
    jsonb_agg(jsonb_build_object('id', t.id, 'talla', t.talla, 'existencia', t.existencia) order by t.talla)
      filter (where t.id is not null),
    '[]'::jsonb) as tallas
from public.productos p
join public.marcas m on m.id = p.marca_id
left join public.producto_tallas t on t.producto_id = p.id
group by p.id, m.nombre;

create view public.v_ventas with (security_invoker = true) as
select
  v.id, v.fecha, v.cliente_id, c.nombre as cliente, c.telefono as cliente_telefono,
  c.problemas as cliente_problemas, v.subtotal, v.ajuste, v.total, v.nota,
  v.creado_por, v.created_at, v.updated_at,
  coalesce(i.lineas, 0)::int as lineas, coalesce(i.unidades, 0)::int as unidades
from public.ventas v
join public.clientes c on c.id = v.cliente_id
left join lateral (
  select count(*) as lineas, sum(cantidad) as unidades from public.venta_items where venta_id = v.id
) i on true;

create view public.v_venta_items with (security_invoker = true) as
select
  vi.id, vi.venta_id, vi.producto_talla_id, vi.cantidad, vi.precio_unitario, vi.subtotal,
  t.talla, p.id as producto_id, p.codigo, p.nombre, m.nombre as marca, p.imagen_url
from public.venta_items vi
join public.producto_tallas t on t.id = vi.producto_talla_id
join public.productos p on p.id = t.producto_id
join public.marcas m on m.id = p.marca_id;

create view public.v_resumen_mensual with (security_invoker = true) as
select
  date_trunc('month', v.fecha at time zone 'America/Guatemala')::date as mes,
  count(*)::int as ventas,
  coalesce(sum(i.unidades), 0)::int as unidades,
  sum(v.subtotal) as subtotal,
  sum(v.ajuste) as ajustes,
  sum(v.total) as total
from public.ventas v
left join lateral (select sum(cantidad) as unidades from public.venta_items where venta_id = v.id) i on true
group by 1;

revoke all on public.v_inventario, public.v_ventas, public.v_venta_items, public.v_resumen_mensual from anon;
grant select on public.v_inventario, public.v_ventas, public.v_venta_items, public.v_resumen_mensual to authenticated;

