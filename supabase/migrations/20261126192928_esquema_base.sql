create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

-- ---------------------------------------------------------------------
-- Usuarios autorizados (lista blanca). Aunque alguien lograra crearse
-- una cuenta en Supabase Auth, sin estar aquí no ve ni toca nada.
-- ---------------------------------------------------------------------
create table public.miembros (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  nombre     text,
  created_at timestamptz not null default now()
);

create or replace function public.es_miembro()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (select 1 from public.miembros where user_id = (select auth.uid()));
$$;

create or replace function private.exigir_miembro()
returns void
language plpgsql stable security definer
set search_path = ''
as $$
begin
  if not public.es_miembro() then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
end;
$$;

-- Los usuarios que ya existen quedan autorizados.
insert into public.miembros (user_id, nombre)
select id, email from auth.users
on conflict do nothing;

-- ---------------------------------------------------------------------
-- Utilidades de triggers
-- ---------------------------------------------------------------------
create or replace function private.tocar_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create or replace function private.normalizar_marca()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.nombre := upper(btrim(new.nombre));
  return new;
end;
$$;

create or replace function private.normalizar_producto()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.codigo := upper(btrim(new.codigo));
  new.nombre := btrim(new.nombre);
  new.descripcion := nullif(btrim(new.descripcion), '');
  return new;
end;
$$;

-- Mantiene lo que hacía la base anterior: nombre de cliente en MAYÚSCULAS.
create or replace function private.normalizar_cliente()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.nombre    := upper(regexp_replace(btrim(new.nombre), '\s+', ' ', 'g'));
  new.telefono  := nullif(regexp_replace(coalesce(new.telefono, ''), '[^0-9+]', '', 'g'), '');
  new.direccion := nullif(btrim(new.direccion), '');
  new.notas     := nullif(btrim(new.notas), '');
  return new;
end;
$$;

-- ---------------------------------------------------------------------
-- Catálogo
-- ---------------------------------------------------------------------
create table public.marcas (
  id         bigint generated by default as identity primary key,
  nombre     text not null,
  created_at timestamptz not null default now(),
  constraint marcas_nombre_unico unique (nombre),
  constraint marcas_nombre_no_vacio check (btrim(nombre) <> '')
);
create trigger normalizar before insert or update on public.marcas
  for each row execute function private.normalizar_marca();

create table public.productos (
  id          bigint generated by default as identity primary key,
  codigo      text not null,
  nombre      text not null,
  marca_id    bigint not null references public.marcas(id),
  descripcion text,
  precio      numeric(10,2) not null check (precio >= 0),
  costo       numeric(10,2) check (costo >= 0),
  imagen_url  text,
  activo      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint productos_codigo_unico unique (codigo),
  constraint productos_codigo_no_vacio check (btrim(codigo) <> ''),
  constraint productos_nombre_no_vacio check (btrim(nombre) <> '')
);
create index productos_marca_idx on public.productos (marca_id);
create trigger normalizar before insert or update on public.productos
  for each row execute function private.normalizar_producto();
create trigger tocar_updated_at before update on public.productos
  for each row execute function private.tocar_updated_at();

-- Una fila por talla de cada producto. La existencia solo cambia por funciones.
create table public.producto_tallas (
  id          bigint generated by default as identity primary key,
  producto_id bigint not null references public.productos(id) on delete cascade,
  talla       numeric(4,1) not null check (talla > 0),
  existencia  integer not null default 0 check (existencia >= 0),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint producto_tallas_unica unique (producto_id, talla)
);
create trigger tocar_updated_at before update on public.producto_tallas
  for each row execute function private.tocar_updated_at();

-- ---------------------------------------------------------------------
-- Clientes
-- ---------------------------------------------------------------------
create table public.clientes (
  id         bigint generated by default as identity primary key,
  nombre     text not null,
  telefono   text,
  direccion  text,
  notas      text,
  problemas  boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint clientes_telefono_unico unique (telefono),
  constraint clientes_nombre_no_vacio check (btrim(nombre) <> '')
);
create index clientes_nombre_idx on public.clientes (nombre);
create trigger normalizar before insert or update on public.clientes
  for each row execute function private.normalizar_cliente();
create trigger tocar_updated_at before update on public.clientes
  for each row execute function private.tocar_updated_at();

-- ---------------------------------------------------------------------
-- Ventas
-- ---------------------------------------------------------------------
create table public.ventas (
  id         bigint generated by default as identity primary key,
  cliente_id bigint not null references public.clientes(id),
  fecha      timestamptz not null default now(),
  subtotal   numeric(10,2) not null default 0 check (subtotal >= 0),
  ajuste     numeric(10,2) not null default 0,   -- descuento (−) o recargo (+)
  total      numeric(10,2) generated always as (subtotal + ajuste) stored,
  nota       text,
  creado_por uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ventas_total_no_negativo check (subtotal + ajuste >= 0)
);
create index ventas_cliente_idx on public.ventas (cliente_id);
create index ventas_fecha_idx on public.ventas (fecha desc);
create trigger tocar_updated_at before update on public.ventas
  for each row execute function private.tocar_updated_at();

create table public.venta_items (
  id                bigint generated by default as identity primary key,
  venta_id          bigint not null references public.ventas(id) on delete cascade,
  producto_talla_id bigint not null references public.producto_tallas(id),
  cantidad          integer not null check (cantidad > 0),
  precio_unitario   numeric(10,2) not null check (precio_unitario >= 0),
  subtotal          numeric(10,2) generated always as (cantidad * precio_unitario) stored,
  created_at        timestamptz not null default now()
);
create index venta_items_venta_idx on public.venta_items (venta_id);
create index venta_items_talla_idx on public.venta_items (producto_talla_id);

-- ---------------------------------------------------------------------
-- Historial de movimientos de inventario (kardex)
-- ---------------------------------------------------------------------
create table public.movimientos_inventario (
  id                    bigint generated by default as identity primary key,
  producto_talla_id     bigint not null references public.producto_tallas(id) on delete cascade,
  tipo                  text not null check (tipo in ('migracion','entrada','ajuste','venta','devolucion')),
  cantidad              integer not null,          -- positiva entra, negativa sale
  existencia_resultante integer not null,
  venta_id              bigint references public.ventas(id) on delete set null,
  nota                  text,
  creado_por            uuid default auth.uid() references auth.users(id) on delete set null,
  created_at            timestamptz not null default now()
);
create index movimientos_talla_idx on public.movimientos_inventario (producto_talla_id, created_at desc);
create index movimientos_venta_idx on public.movimientos_inventario (venta_id);
create index movimientos_creado_por_idx on public.movimientos_inventario (creado_por);
create index ventas_creado_por_idx on public.ventas (creado_por);

