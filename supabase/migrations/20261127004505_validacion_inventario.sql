-- =====================================================================
-- Validación de inventario: conteo físico por marca, talla por talla.
-- - Una validación abierta por marca; el avance se guarda y se retoma desde cualquier teléfono.
-- - Al terminar una talla, lo no contado cuenta como 0.
-- - Al cerrar, la existencia queda = lo contado + lo que se movió después de contar (ventas, etc.).
-- =====================================================================

alter table public.movimientos_inventario drop constraint movimientos_inventario_tipo_check;
alter table public.movimientos_inventario add constraint movimientos_inventario_tipo_check
  check (tipo in ('migracion','entrada','ajuste','venta','devolucion','conteo'));

create table public.conteos (
  id          bigint generated by default as identity primary key,
  marca_id    bigint not null references public.marcas(id),
  estado      text not null default 'abierto' check (estado in ('abierto','cerrado','cancelado')),
  nota        text,
  resumen     jsonb,
  creado_por  uuid default auth.uid() references auth.users(id) on delete set null,
  cerrado_por uuid references auth.users(id) on delete set null,
  created_at  timestamptz not null default now(),
  cerrado_at  timestamptz
);
create unique index conteos_una_abierta_por_marca on public.conteos (marca_id) where estado = 'abierto';
create index conteos_marca_idx on public.conteos (marca_id, created_at desc);
create index conteos_creado_por_idx on public.conteos (creado_por);
create index conteos_cerrado_por_idx on public.conteos (cerrado_por);

create table public.conteo_tallas (
  conteo_id     bigint not null references public.conteos(id) on delete cascade,
  talla         numeric(4,1) not null,
  terminada     boolean not null default false,
  terminado_por uuid references auth.users(id) on delete set null,
  terminado_at  timestamptz,
  primary key (conteo_id, talla)
);
create index conteo_tallas_terminado_por_idx on public.conteo_tallas (terminado_por);

create table public.conteo_lineas (
  conteo_id         bigint not null references public.conteos(id) on delete cascade,
  producto_talla_id bigint not null references public.producto_tallas(id) on delete cascade,
  contado           integer not null check (contado >= 0),
  contado_por       uuid default auth.uid() references auth.users(id) on delete set null,
  updated_at        timestamptz not null default now(),
  primary key (conteo_id, producto_talla_id)
);
create index conteo_lineas_talla_idx on public.conteo_lineas (producto_talla_id);
create index conteo_lineas_contado_por_idx on public.conteo_lineas (contado_por);

alter table public.conteos       enable row level security;
alter table public.conteo_tallas enable row level security;
alter table public.conteo_lineas enable row level security;
revoke all on public.conteos, public.conteo_tallas, public.conteo_lineas from anon;
revoke insert, update, delete, truncate on public.conteos, public.conteo_tallas, public.conteo_lineas from authenticated;
create policy miembros_leen on public.conteos       for select to authenticated using ((select public.es_miembro()));
create policy miembros_leen on public.conteo_tallas for select to authenticated using ((select public.es_miembro()));
create policy miembros_leen on public.conteo_lineas for select to authenticated using ((select public.es_miembro()));

-- ---------------------------------------------------------------------
-- Vista: validaciones con su avance
-- ---------------------------------------------------------------------
create view public.v_conteos with (security_invoker = true) as
select c.id, c.marca_id, m.nombre as marca, c.estado, c.nota, c.resumen, c.created_at, c.cerrado_at,
       (select count(*) from public.conteo_tallas ct where ct.conteo_id = c.id)::int as tallas_total,
       (select count(*) from public.conteo_tallas ct where ct.conteo_id = c.id and ct.terminada)::int as tallas_terminadas,
       (select count(*) from public.conteo_lineas cl where cl.conteo_id = c.id)::int as lineas_contadas
from public.conteos c
join public.marcas m on m.id = c.marca_id;
revoke all on public.v_conteos from anon, authenticated;
grant select on public.v_conteos to authenticated;

-- ---------------------------------------------------------------------
-- Funciones
-- ---------------------------------------------------------------------
create or replace function private.conteo_abierto(p_conteo_id bigint)
returns public.conteos language plpgsql stable security definer set search_path = '' as $$
declare v public.conteos;
begin
  select * into v from public.conteos where id = p_conteo_id;
  if not found then raise exception 'La validación % no existe', p_conteo_id using errcode = 'P0002'; end if;
  if v.estado <> 'abierto' then raise exception 'Esta validación ya está %', v.estado using errcode = '22023'; end if;
  return v;
end; $$;

-- Abre (o retoma) la validación de una marca.
create or replace function public.iniciar_conteo(p_marca_id bigint)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_id bigint;
begin
  perform private.exigir_miembro();
  if not exists (select 1 from public.marcas where id = p_marca_id) then
    raise exception 'La marca no existe' using errcode = 'P0002';
  end if;
  select id into v_id from public.conteos where marca_id = p_marca_id and estado = 'abierto';
  if v_id is not null then return v_id; end if;

  insert into public.conteos (marca_id) values (p_marca_id) returning id into v_id;
  insert into public.conteo_tallas (conteo_id, talla)
  select distinct v_id, t.talla
    from public.producto_tallas t join public.productos p on p.id = t.producto_id
   where p.marca_id = p_marca_id and p.activo;
  return v_id;
end; $$;

-- Guarda cuántos pares se encontraron de un modelo en una talla.
create or replace function public.registrar_conteo(p_conteo_id bigint, p_producto_talla_id bigint, p_contado integer)
returns void language plpgsql security definer set search_path = '' as $$
declare v public.conteos; v_talla numeric;
begin
  perform private.exigir_miembro();
  v := private.conteo_abierto(p_conteo_id);
  if p_contado is null or p_contado < 0 then raise exception 'Cantidad inválida' using errcode = '22023'; end if;
  select t.talla into v_talla from public.producto_tallas t join public.productos p on p.id = t.producto_id
   where t.id = p_producto_talla_id and p.marca_id = v.marca_id;
  if not found then raise exception 'Ese producto no es de la marca que se está validando' using errcode = '22023'; end if;

  insert into public.conteo_lineas (conteo_id, producto_talla_id, contado)
  values (p_conteo_id, p_producto_talla_id, p_contado)
  on conflict (conteo_id, producto_talla_id)
  do update set contado = excluded.contado, contado_por = auth.uid(), updated_at = now();

  -- Asegura que la talla exista en la validación (por si se agregó una talla nueva a la marca).
  insert into public.conteo_tallas (conteo_id, talla) values (p_conteo_id, v_talla) on conflict do nothing;
end; $$;

-- Marca una talla como terminada (lo no contado cuenta como 0) o la reabre.
create or replace function public.marcar_talla_conteo(p_conteo_id bigint, p_talla numeric, p_terminada boolean)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform private.exigir_miembro();
  perform private.conteo_abierto(p_conteo_id);
  insert into public.conteo_tallas (conteo_id, talla, terminada, terminado_por, terminado_at)
  values (p_conteo_id, p_talla, p_terminada, case when p_terminada then auth.uid() end, case when p_terminada then now() end)
  on conflict (conteo_id, talla) do update
    set terminada = excluded.terminada, terminado_por = excluded.terminado_por, terminado_at = excluded.terminado_at;
end; $$;

-- Calcula lo que quedaría al cerrar (sin aplicar nada). Sirve para el resumen previo.
create or replace function public.previa_conteo(p_conteo_id bigint)
returns table (producto_talla_id bigint, producto_id bigint, codigo text, nombre text, imagen_url text,
               talla numeric, sistema integer, contado integer, movido_despues integer, final integer)
language plpgsql stable security definer set search_path = '' as $$
declare v public.conteos;
begin
  perform private.exigir_miembro();
  select * into v from public.conteos where id = p_conteo_id;
  if not found then raise exception 'La validación % no existe', p_conteo_id using errcode = 'P0002'; end if;
  return query
  with base as (
    select t.id as pt_id, p.id as p_id, p.codigo as p_codigo, p.nombre as p_nombre, p.imagen_url as p_imagen, t.talla as t_talla, t.existencia,
           cl.contado as c_contado, cl.updated_at as contado_at, ct.terminado_at
      from public.producto_tallas t
      join public.productos p on p.id = t.producto_id
      join public.conteo_tallas ct on ct.conteo_id = p_conteo_id and ct.talla = t.talla and ct.terminada
      left join public.conteo_lineas cl on cl.conteo_id = p_conteo_id and cl.producto_talla_id = t.id
     where p.marca_id = v.marca_id and p.activo
  ), calc as (
    select b.*, coalesce((
        select sum(m.cantidad) from public.movimientos_inventario m
         where m.producto_talla_id = b.pt_id
           and m.created_at > coalesce(b.contado_at, b.terminado_at)
           and m.tipo <> 'conteo'
      ), 0)::integer as despues
      from base b
  )
  select calc.pt_id, calc.p_id, calc.p_codigo, calc.p_nombre, calc.p_imagen, calc.t_talla, calc.existencia,
         coalesce(calc.c_contado, 0), calc.despues, greatest(0, coalesce(calc.c_contado, 0) + calc.despues)
    from calc
   order by calc.t_talla, calc.p_nombre;
end; $$;

-- Cierra la validación y ajusta las existencias (solo tallas terminadas).
create or replace function public.cerrar_conteo(p_conteo_id bigint, p_nota text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v public.conteos; r record; v_actual int; v_sube int := 0; v_baja int := 0; v_igual int := 0; v_pares_antes int := 0; v_pares_despues int := 0; v_resumen jsonb;
begin
  perform private.exigir_miembro();
  v := private.conteo_abierto(p_conteo_id);
  perform 1 from public.conteos where id = p_conteo_id for update;
  if exists (select 1 from public.conteo_tallas where conteo_id = p_conteo_id and not terminada) then
    raise exception 'Faltan tallas por terminar' using errcode = '22023';
  end if;

  for r in select * from public.previa_conteo(p_conteo_id) x order by x.producto_talla_id loop
    v_pares_antes := v_pares_antes + r.sistema;
    v_pares_despues := v_pares_despues + r.final;
    if r.final > r.sistema then v_sube := v_sube + 1;
    elsif r.final < r.sistema then v_baja := v_baja + 1;
    else v_igual := v_igual + 1; end if;
    -- Se compara contra la existencia actual (bloqueada) por si hubo una venta en este instante.
    select existencia into v_actual from public.producto_tallas where id = r.producto_talla_id for update;
    perform private.mover_existencia(r.producto_talla_id, r.final - v_actual, 'conteo', null,
      format('Validación de inventario #%s', p_conteo_id));
  end loop;

  v_resumen := jsonb_build_object('tallas_revisadas', v_sube + v_baja + v_igual, 'con_mas', v_sube, 'con_menos', v_baja,
    'correctas', v_igual, 'pares_antes', v_pares_antes, 'pares_despues', v_pares_despues);
  update public.conteos set estado = 'cerrado', cerrado_por = auth.uid(), cerrado_at = now(),
         nota = nullif(btrim(p_nota), ''), resumen = v_resumen
   where id = p_conteo_id;
  return v_resumen;
end; $$;

create or replace function public.cancelar_conteo(p_conteo_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform private.exigir_miembro();
  perform private.conteo_abierto(p_conteo_id);
  update public.conteos set estado = 'cancelado', cerrado_por = auth.uid(), cerrado_at = now() where id = p_conteo_id;
end; $$;

revoke all on function private.conteo_abierto(bigint) from public, anon, authenticated;
revoke execute on function
  public.iniciar_conteo(bigint), public.registrar_conteo(bigint, bigint, integer),
  public.marcar_talla_conteo(bigint, numeric, boolean), public.previa_conteo(bigint),
  public.cerrar_conteo(bigint, text), public.cancelar_conteo(bigint)
from public, anon;
grant execute on function
  public.iniciar_conteo(bigint), public.registrar_conteo(bigint, bigint, integer),
  public.marcar_talla_conteo(bigint, numeric, boolean), public.previa_conteo(bigint),
  public.cerrar_conteo(bigint, text), public.cancelar_conteo(bigint)
to authenticated;
